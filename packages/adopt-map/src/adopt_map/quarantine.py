"""The five-step pipeline between a model's reply and a human -- `04` §6.

```
GlueOutput(authored)
  -> 1. STATIC AUDIT   reject -> DISCARD, agent_output_rejected(rule), no file written
  -> 2. WRITE          .adopt/extractors/<id>.py and tests/test_<id>.py
  -> 3. SANDBOX RUN    crash/timeout -> quarantine_failed, file kept for the reviewer
  -> 4. FACTS          .adopt/out/quarantine/facts.json  -- NEVER the store
  -> 5. REVIEW ROW     .adopt/out/quarantine/review.json
```

**Step 1 runs before step 2, and the ordering is the security property.** A
module that fails the audit is never written to disk at all -- not to a scratch
path, not to a temp file, not "for the reviewer to see what was rejected". `04`
§6 says *"DISCARD, record `agent_output_rejected(rule)`. No file written."*, and
the rule that survives review pressure is the one where the rejected artefact
does not exist to be recovered.

**Nothing here can reach the store, and it is structural rather than careful.**
This module imports no writer, no port and no store handle; the only paths it
knows are under `.adopt/`. `01` F12.3's *"never to the store, until
`adopt extractors review <id> --approve`"* is therefore not a rule this code
follows -- it is a capability this code does not have. The same argument
`SurfaceFact` makes by having no `uri` field.

**`--approve` is refused when the file differs from the generated original.**
`04` §6 states why, and it is worth restating because it looks like friction and
is actually the measurement: without the refusal, a reviewer patches a module
into working order and approves it, the rewrite is never recorded, and ADR-0.1's
>40% reversal trigger can never fire. The digest of the generated bytes is
written beside the module at generation time, so the comparison does not depend
on the ledger being intact.
"""

